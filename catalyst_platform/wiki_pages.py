@dataclass(frozen=True)
class Page:
    path: str
    kind: str
    title: str
    content: str

    @property
    def sha256(self) -> str:
        return hashlib.sha256(self.content.encode("utf-8")).hexdigest()


@dataclass(frozen=True)
class PageSet:
    pages: tuple[Page, ...]
    stats: dict[str, Any] = field(default_factory=dict)
    # Which store, which version, which renderer produced these pages. None only for a page
    # set a caller assembled by hand; every projection fills it.
    identity: dict[str, Any] | None = None

    def __iter__(self):
        return iter(self.pages)

    def __len__(self) -> int:
        return len(self.pages)

    def by_path(self) -> dict[str, Page]:
        return {page.path: page for page in self.pages}

    def of_kind(self, kind: str) -> tuple[Page, ...]:
        return tuple(page for page in self.pages if page.kind == kind)


def _frontmatter(fields: Sequence[tuple[str, Any]]) -> str:
    lines = ["---"]
    for key, value in fields:
        if value is None:
            continue
        if isinstance(value, (list, tuple)):
            rendered = "[" + ", ".join(json.dumps(item, ensure_ascii=False) for item in value) + "]"
            lines.append(f"{key}: {rendered}")
        elif isinstance(value, bool):
            lines.append(f"{key}: {'true' if value else 'false'}")
        elif isinstance(value, (int, float)):
            lines.append(f"{key}: {value}")
        else:
            lines.append(f"{key}: {json.dumps(str(value), ensure_ascii=False)}")
    lines.append("---")
    return "\n".join(lines)


def _short(value: Any, length: int = 12) -> str:
    text = str(value or "")
    return text[:length]


def _safe(name: str) -> str:
    cleaned = "".join(char if char.isalnum() or char in "-_." else "-" for char in name)
    return cleaned.strip("-.") or "page"


def _line_locator(evidence: Mapping[str, Any]) -> str | None:
    """`line:N` or `line:N-M` for the span this evidence now points at, when it has a usable one."""
    start = evidence.get("line_start")
    if not isinstance(start, int) or start < 1:
        return None
    end = evidence.get("line_end")
    if isinstance(end, int) and end > start:
        return f"line:{start}-{end}"
    return f"line:{start}"


def _evidence_line(evidence: Mapping[str, Any], source_titles: Mapping[str, str]) -> str:
    """One citation line: the address it points at now, and what is known about it.

    For every status but ``relocated`` the address is the one the store recorded - showing a
    citation as it was recorded is the point of a citation. A relocated one is different: its
    text was found again in a newer revision, so the recorded address now points at lines that
    may hold something else entirely. The address has to be the span it moved *to*, or a reader
    follows the link, lands on the old line and believes the quote was checked there. Where it
    came from stays in the status (``relocated from line:N``), which is a history, not an
    address, and the two revisions are shown so "still there, moved" cannot be read as
    "observed there just now".
    """
    source_id = str(evidence.get("source_id") or "")
    title = source_titles.get(source_id, source_id)
    locator = evidence.get("locator") or (
        f"line:{evidence.get('line_start')}" if evidence.get("line_start") else "unknown location"
    )
    status = str(evidence.get("freshness_status", "unknown"))
    revision = _short(evidence.get("source_revision"))
    if status == "relocated":
        locator = _line_locator(evidence) or locator
        revision = (f"{_short(evidence.get('relocated_from_revision'))}->"
                    f"{_short(evidence.get('target_revision'))}")
        status = f"relocated from line:{evidence.get('relocated_from_line')}"
    return (f"- `{title}` @ `{locator}` "
            f"(revision {revision}, {status}, "
            f"{evidence.get('evidence_class', 'observed_from_source')})")


def scan_sources(wiki: Any) -> dict[str, tuple[_TextUnit, ...]]:
    """Extract every readable staged source once; the mention layer works from this."""
    units: dict[str, tuple[_TextUnit, ...]] = {}
    for source in wiki.sources():
        source_id = str(source.get("source_id"))
        if source.get("status") == "WITHDRAWN":
            continue
        record = wiki.source_record(source_id)
        relative = str(record.get("relative_path") or "")
        path = next((root / relative for root in wiki.roots if (root / relative).is_file()), None)
        if path is None:
            continue
        try:
            extracted, _report = extract_with_report(
                path, relative, source_id, str(record.get("revision") or ""), raw=path.read_bytes()
            )
        except (ValueError, OSError):
            continue
        units[source_id] = tuple(extracted)
    return units


def _read(wiki: Any, name: str, default: Any) -> Any:
    """Read one optional surface of the store.

    A store that does not offer the surface at all - no such read method - gets the default:
    that is a narrower interface, not a failure, and the pages that need it are simply absent.
    A store that offers it and then fails propagates the failure. Returning a default there
    would publish a page set with no concepts, or no authority, as if the whole store had been
    read, and that silent omission is the opposite of what a projection is for.
    """
    reader = getattr(wiki, name, None)
    if not callable(reader):
        return default
    return reader()


def _semantic_ledger(wiki: Any) -> Mapping[str, Any]:
    state = _read(wiki, "semantic_state", {})
    return state if isinstance(state, Mapping) else {}


def _authority(accepted: Mapping[str, Any], state: Mapping[str, Any]) -> dict[str, Any]:
    """What makes what a page shows trustworthy: the accepted version and who accepted it."""
    active_id = accepted.get("active_version_id")
    versions = state.get("accepted_versions") or {}
    record = versions.get(active_id) if isinstance(active_id, str) and isinstance(versions, Mapping) else None
    record = record if isinstance(record, Mapping) else {}
    return {
        "version_id": active_id if isinstance(active_id, str) else None,
        "authority_class": record.get("authority_class"),
        "source_id": record.get("source_id"),
        "source_revision": record.get("source_revision"),
    }


def _authority_lines(authority: Mapping[str, Any] | None) -> list[str]:
    """The banner every knowledge page carries: which version, whose acceptance."""
    if not authority or not authority.get("version_id"):
        return ["> 权威：本 scope 还没有已接受的版本；页面上不会出现候选内容。", ""]
    return [f"> 权威：已接受版本 `{authority['version_id']}`"
            f"（作者类别 `{authority.get('authority_class') or 'unknown'}`）；"
            "本页是投影，不产生新的知识。", ""]


def renderer_identity() -> dict[str, Any]:
    """Who rendered these pages, precisely enough to tell two builds apart.

    ``PROJECTION_VERSION`` names the contract the pages promise, not the code that produced
    them: two builds can honour the same contract and still lay a page out differently. The
    module's own digest is the implementation version, and it costs one file read per process.
    """
    global _RENDERER_SOURCE_SHA256
    if _RENDERER_SOURCE_SHA256 is None:
        try:
            _RENDERER_SOURCE_SHA256 = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
        except OSError:
            _RENDERER_SOURCE_SHA256 = ""
    return {
        "name": RENDERER_NAME,
        "version": PROJECTION_VERSION,
        "source_sha256": _RENDERER_SOURCE_SHA256 or None,
    }


def _identity(wiki: Any, accepted: Mapping[str, Any], concept_set: Any, *,
              digest: str | None, attempts: int) -> dict[str, Any]:
    """What this projection was computed from, in terms a page tree can be checked against."""
    roots = getattr(wiki, "roots", ()) or ()
    return {
        "scope_id": getattr(wiki, "scope_id", None),
        "backend": getattr(wiki, "backend", None),
        "store_index_sha256": digest,
        "active_version_id": accepted.get("active_version_id"),
        "concept_set_version": getattr(concept_set, "version_id", None),
        "source_roots": [str(root) for root in roots],
        # Which check backed the digest above, so nobody has to guess what was and was not
        # proven: `index_digest_before_and_after` is an optimistic window, not a transaction.
        "snapshot": {
            "method": "index_digest_before_and_after" if digest is not None else "none",
            "attempts": attempts,
        },
        "renderer": renderer_identity(),
    }


def project(wiki: Any, *, scan: Mapping[str, Sequence[_TextUnit]] | None = None,
            root: Path | str | None = None, scan_store: bool = False) -> PageSet:
    """Render the whole wiki inside an index stability window; deterministic and model-free.

    The window is an optimistic check, not a transaction. The store's index digest is read
    before and after the work, and a projection whose two ends disagree is retried once and
    then refused, because publishing pages from generation A under the digest of generation B
    is worse than publishing nothing. What that catches is the ordinary case: a commit landing
    while the pages are being built. What it cannot catch is worth naming. A commit that lands
    and is reverted inside the window returns the same digest (A -> B -> A), and a source file
    read during the projection can change without the index changing at all.

    So the pages, the version and the digest are *reported* as one index generation, and
    ``identity.snapshot.method`` names exactly which check was made. A caller that needs a
    strict snapshot has to freeze the store; this window only says nobody committed to it
    while it was read.

    ``scan_store`` computes the mention scan inside the same window, so a mention is read from
    the same index generation as the pages. The source *files* it extracts are outside that
    guarantee: a source rewritten while it is being read can still supply a quote the store
    never recorded. A caller that passes ``scan`` does so from a read of its own; the identity
    then describes the store, and the scan is whatever that caller can vouch for.
    """
    digest_reader = getattr(wiki, "index_digest", None)
    if not callable(digest_reader):
        return _project_once(wiki, scan=scan, root=root, scan_store=scan_store,
                             digest=None, attempts=1)
    for attempt in range(1, SNAPSHOT_ATTEMPTS + 1):
        digest = digest_reader()
        pages = _project_once(wiki, scan=scan, root=root, scan_store=scan_store,
                              digest=digest, attempts=attempt)
        if digest_reader() == digest:
            return pages
    raise WikiUnavailable(
        "the local Wiki changed while its pages were being projected; nothing was published"
    )


def _project_once(wiki: Any, *, scan: Mapping[str, Sequence[_TextUnit]] | None,
                  root: Path | str | None, scan_store: bool,
                  digest: str | None, attempts: int) -> PageSet:
    """One pass over the store. Only `project` may call this: it is what the window wraps."""
    accepted = wiki.accepted_meanings()
    if scan_store:
        scan = scan_sources(wiki)
    # A citation that went stale because its source changed may still point at the same text.
    # The overlay says where that text is now; it changes nothing but this rendering.
    meanings = apply_relocations(accepted["meanings"], RelocationResolver(wiki))
    scan = scan or {}
    index = EntityIndex.from_meanings(meanings)

    sources = [row for row in wiki.sources() if row.get("status") != "WITHDRAWN"]
    source_titles = {str(row["source_id"]): str(row.get("relative_path") or row["source_id"])
                     for row in sources}

    state = _semantic_ledger(wiki)
    authority = _authority(accepted, state)
    concept_set = _read(wiki, "concept_set", None)
    concept_state = _read(wiki, "concept_state", {})

    pages: list[Page] = []
    entity_pages, object_stats = _entity_pages(meanings, index, scan, source_titles, authority)
    pages.extend(entity_pages)
    pages.extend(_concept_pages(meanings, concept_set, concept_state))
    pages.extend(_version_pages(state))
    pages.extend(_source_pages(sources, scan, index, present=_present_sources(wiki, sources)))
    page_stats = {
        "sources": len(sources),
        "meanings": len(meanings),
        "entities": sum(1 for row in meanings if row.get("kind") == "entity"),
        "relations": sum(1 for row in meanings if row.get("kind") == "relation"),
        "claims": sum(1 for row in meanings if row.get("kind") in {"claim", "condition", "exception", "unknown"}),
        "versions": len([row for row in (state.get("accepted_versions") or {}).values()
                         if isinstance(row, Mapping)]),
        # Counted by the projection itself: a row nothing was saved against is reported,
        # never hung on the nearest object and never dropped.
        **object_stats,
        "scanned_sources": sorted(scan),
    }
    pages.append(_gaps_page(wiki, meanings, sources, concept_set, concept_state, state))
    pages.append(_overview_page(wiki, meanings, sources, page_stats, accepted))
    pages.append(_log_page(wiki))
    pages.append(_index_page(pages, root))
    # Every link in the set was written by this projection, so the set itself is what the links
    # resolve against: a title with no page is a gap in the rendering, a title with two is a
    # name the set cannot resolve. It is reported, not repaired - the label is the store's.
    page_stats["links"] = link_report(pages)
    return PageSet(pages=tuple(pages), stats=page_stats,
                   identity=_identity(wiki, accepted, concept_set, digest=digest, attempts=attempts))


def _object_lines(view: ObjectView) -> list[str]:
    """One object as a reader needs it: what it says, who holds it, and why it is not confirmed.

    The qualification lines are the row's own; nothing is re-derived here, so a pending duty
    cannot read as approved because its evidence happened to look complete.
    """
    lines = [f"- **{view.statement or '（这句话为空）'}**"]
    if view.roles:
        for role in view.roles:
            if role.resolved:
                via = f"，经 `{role.via}`" if role.via else ""
                lines.append(f"  - {role.label}：{role.title}（`{role.page}`{via}）")
            else:
                lines.append(f"  - {role.label}：`{role.key}`（这一版里没有对应实体页，键照原样保留）")
    else:
        lines.append("  - 未挂到对象：这一条没有记录持有者或适用对象，键照原样保留，不挂到最近的实体")
    if view.unattached:
        lines.append(f"  - 挂靠：未挂到对象（{unattached_reason(view)}）")
    lines.append(f"  - 资格：{view.qualification_label}；依据：{view.basis_label}（`{view.basis or '未记录'}`）")
    state = f"；范围状态：`{view.scope_state}`" if view.scope_state else ""
    lines.append(f"  - 校验：{view.verification_label}{state}")
    # What the row itself recorded as open. A row that recorded nothing says exactly that;
    # the page does not turn silence into a question or into a confirmation.
    if view.unsettled:
        source = "原文" if view.unsettled_source == "observed_absence" else "记录"
        lines.append(f"  - 尚未确认（{source}）：{view.unsettled}")
    else:
        lines.append("  - 尚未确认：没有记录未确认项")
    if view.citations:
        for citation in view.citations:
            lines.append(f"  - 依据行：{citation.line()}")
    else:
        lines.append("  - 依据行：这一条没有记录引用（证据类别未解析），页面不代它补一条")
    lines.append(f"  - 条目：`{view.identity.get('meaning_id') or '未记录'}`"
                 f"（来源：{'已接受版本' if view.origin == 'accepted_meaning' else '候选条目'}）")
    return lines


def _entity_pages(meanings: Sequence[Mapping[str, Any]], index: EntityIndex,
                  scan: Mapping[str, Sequence[_TextUnit]],
                  source_titles: Mapping[str, str],
                  authority: Mapping[str, Any] | None = None
                  ) -> tuple[list[Page], dict[str, Any]]:
    entities = [row for row in meanings if row.get("kind") == "entity" and isinstance(row.get("canonical_id"), str)]
    aliases: dict[str, list[str]] = {}
    for row in meanings:
        if row.get("kind") == "alias" and isinstance(row.get("canonical_id"), str):
            aliases.setdefault(row["canonical_id"], []).append(str(row.get("meaning") or ""))
    relations = [row for row in meanings if row.get("kind") == "relation"]
    titles = {row["canonical_id"]: str(row.get("meaning") or row.get("key") or row["canonical_id"])
              for row in entities}
    # A saved role names an entity by its producer key; the page a reader can open is the one
    # this loop is about to write. Both spellings resolve to the same page, and a key this
    # version cannot resolve stays a key instead of being matched to a similar-looking name.
    entity_pages: dict[str, tuple[str, str]] = {}
    for row in entities:
        path = f"entities/{_safe(str(row.get('canonical_key') or row.get('key') or row['canonical_id']))}.md"
        title = titles[row["canonical_id"]]
        for key in (row.get("key"), row.get("canonical_key"), row.get("canonical_id")):
            if isinstance(key, str) and key:
                entity_pages.setdefault(key, (title, path))
    objects = collect(meanings, entities=entity_pages, titles=source_titles)

    mentions_by_canonical: dict[str, list[tuple[str, str, str]]] = {}
    seen_mentions: set[tuple[str, str, str]] = set()
    for source_id, units in scan.items():
        for unit in units:
            for mention in index.match(unit.quote or "").mentions:
                key = (mention.canonical_id, source_id, unit.locator)
                if key in seen_mentions:
                    continue
                seen_mentions.add(key)
                mentions_by_canonical.setdefault(mention.canonical_id, []).append(
                    (source_titles.get(source_id, source_id), unit.locator,
                     "ambiguous" if mention.ambiguous else "confident")
                )

    pages = []
    for entity in entities:
        canonical_id = entity["canonical_id"]
        title = titles[canonical_id]
        canonical_key = str(entity.get("canonical_key") or entity.get("key") or canonical_id)
        own_relations = [row for row in relations
                         if row.get("canonical_subject_id") == canonical_id
                         or row.get("canonical_object_id") == canonical_id]
        mention_rows = mentions_by_canonical.get(canonical_id, [])
        ambiguous = [row for row in mention_rows if row[2] == "ambiguous"]
        mine = attached_to(objects, str(entity.get("key") or ""))
        duty_rows = [view for view in mine if view.kind == "duty"]
        event_rows = [view for view in mine if view.kind == "event"]
        condition_rows = [view for view in mine if view.kind == "condition"]

        fields = [
            ("type", _ENTITY),
            ("title", title),
            ("canonical_key", canonical_key),
            ("canonical_id", canonical_id),
            ("business_type", entity.get("business_type") or "unknown"),
            ("aliases", sorted(set(aliases.get(canonical_id, [])))),
            ("freshness", entity.get("freshness_status") or "unknown"),
            ("evidence_count", len(entity.get("evidence") or [])),
            ("mention_count", len(mention_rows)),
            ("duty_count", len(duty_rows)),
            ("event_count", len(event_rows)),
            ("condition_count", len(condition_rows)),
            ("version_id", (authority or {}).get("version_id")),
            ("authority_class", (authority or {}).get("authority_class")),
        ]
        if entity.get("confirmed_by_absence"):
            # Only written when it is true, so every other page keeps its exact bytes.
            fields.append(("confirmed_by_absence", True))
        fields.append(("generated_from", f"{PROJECTION_VERSION}:{entity.get('meaning_id')}"))
        body = [_frontmatter(fields), "", f"# {title}", ""]
        body.extend(_authority_lines(authority))

        if aliases.get(canonical_id):
            body.append("## 其他写法")
            body.extend(f"- {name}" for name in sorted(set(aliases[canonical_id])))
            body.append("")

        body.append("## 关系")
        if own_relations:
            for row in own_relations:
                subject = titles.get(str(row.get("canonical_subject_id")), str(row.get("subject_key") or "?"))
                object_ = titles.get(str(row.get("canonical_object_id")), str(row.get("object_key") or "?"))
                predicate = str(row.get("predicate_key") or row.get("predicate") or "相关")
                span = (row.get("evidence") or [{}])[0]
                body.append(f"- {subject} —{predicate}→ {object_} `{span.get('locator') or 'locator unknown'}`")
        else:
            body.append("- 已接受的知识里还没有以它为主语或宾语的关系。")
        body.append("")

        body.append("## 职责")
        body.extend(line for view in duty_rows for line in _object_lines(view))
        if not duty_rows:
            body.append("- 已接受的知识里没有以它持有的职责。")
        body.append("")
        body.append("## 参与事件")
        body.extend(line for view in event_rows for line in _object_lines(view))
        if not event_rows:
            body.append("- 已接受的知识里没有以它为起点或终点的事件。")
        body.append("")
        body.append("## 条件与资格")
        body.extend(line for view in condition_rows for line in _object_lines(view))
        if not condition_rows:
            body.append("- 已接受的知识里没有挂在它名下的条件或例外。")
        body.append("")

        if entity.get("confirmed_by_absence"):
            body.append("> 这次重读没有提到它，但它的原文仍在被接受的修订里：按「未提及即保留」留下"
                        "（`confirmed_by_absence`），不是模型重新确认的。")
            body.append("")

        body.append("## 证据")
        for evidence in entity.get("evidence") or []:
            body.append(_evidence_line(evidence, source_titles))
        if not entity.get("evidence"):
            body.append("- 本条没有逐行证据（不应出现；请检查提交来源）。")
        body.append("")

        body.append("## 出现位置")
        confident = [row for row in mention_rows if row[2] == "confident"]
        for title_, locator, _kind in confident[:40]:
            body.append(f"- `{title_}` @ `{locator}`")
        if len(confident) > 40:
            body.append(f"- …另有 {len(confident) - 40} 处未列出")
        if not confident:
            body.append("- 文本提及索引没有命中：已扫描的来源里没有出现它的可信写法。"
                        "这不等同于「没有来源依据」——扫描提及与结构化证据是两个索引，命中数各自列在下面。")
        body.append("")

        body.append("## 未确认")
        if ambiguous:
            body.append(f"- {len(ambiguous)} 处提及命中的是短名或通用词，**不作为识别**：")
            for title_, locator, _kind in ambiguous[:10]:
                body.append(f"  - `{title_}` @ `{locator}`")
        else:
            body.append("- 没有待消歧的提及记录（扫描提及索引为空；它既不证明没有歧义，也不证明没有依据）。")
        body.append("")

        pages.append(Page(path=f"entities/{_safe(canonical_key)}.md", kind=_ENTITY,
                          title=title, content="\n".join(body)))
    # Counted from the same views the pages were written from, so "on a page" and "not on a
    # page" cannot disagree with what a reader saw.
    lost = unattached(objects)
    stats = {
        "duties": sum(1 for view in objects if view.kind == "duty"),
        "events": sum(1 for view in objects if view.kind == "event"),
        "conditions": sum(1 for view in objects if view.kind == "condition"),
        "unattached": [f"`{view.identity.get('key') or view.identity.get('meaning_id')}`"
                       f"（{unattached_reason(view)}）" for view in lost],
    }
    return pages, stats


def _type_members(meanings: Sequence[Mapping[str, Any]],
                  concept_state: Mapping[str, Any] | None) -> dict[str, list[str]]:
    """Members by the concept a reviewer would call their type, not by the raw spelling."""
    by_type: dict[str, list[str]] = {}
    resolve = None
    if isinstance(concept_state, Mapping) and concept_state:
        from .ontology_concepts import resolve_concept_in

        def resolve(value: object) -> str | None:
            concept = resolve_concept_in(concept_state, value)
            return concept.concept_id if concept is not None else None
    for row in meanings:
        if row.get("kind") != "entity":
            continue
        business_type = row.get("business_type")
        if not isinstance(business_type, str) or not business_type:
            continue
        type_id = (resolve(business_type) if resolve is not None else None) or business_type
        by_type.setdefault(str(type_id), []).append(str(row.get("meaning") or ""))
    return by_type


def _declared_structure_lines(concept: Any) -> list[str]:
    """What the type says about its instances, section by section."""
    lines: list[str] = []
    if concept.attributes:
        lines.append("### 属性")
        lines.extend(
            f"- `{row.name}` · {row.value_type}" + ("（必填）" if row.required else "")
            + (f" — {row.description}" if row.description else "")
            for row in concept.attributes)
        lines.append("")
    if concept.relations:
        lines.append("### 关系")
        lines.extend(
            f"- `{row.predicate}` → `{row.target}`（{'多' if row.cardinality == 'many' else '一'}）"
            + (f" — {row.description}" if row.description else "")
            for row in concept.relations)
        lines.append("")
    if concept.constraints:
        lines.append("### 约束")
        lines.extend(f"- [{row.severity}] {row.statement}" for row in concept.constraints)
        lines.append("")
    if concept.actions:
        lines.append("### 动作")
        lines.extend(f"- {row.name}" + (f" — {row.description}" if row.description else "")
                     for row in concept.actions)
        lines.append("")
    if concept.metrics:
        lines.append("### 指标")
        lines.extend(f"- {row.name}" + (f"（{row.unit}）" if row.unit else "")
                     + (f" — {row.definition}" if row.definition else "") for row in concept.metrics)
        lines.append("")
    return lines


def _declared_gaps(concept: Any, meanings: Sequence[Mapping[str, Any]]) -> list[str]:
    """What the type declares that the accepted version does not yet record."""
    kinds = {str(row.get("kind")) for row in meanings}
    gaps: list[str] = []
    if concept.attributes:
        gaps.append(f"- 属性 {len(concept.attributes)} 个：本版不记录属性取值，声明还只是声明。")
    if concept.constraints and "constraint" not in kinds:
        gaps.append(f"- 约束 {len(concept.constraints)} 条：本版没有一条 constraint 条目，约束还没落到被接受的知识上。")
    if concept.actions and "action" not in kinds:
        gaps.append(f"- 动作 {len(concept.actions)} 个：本版没有一条 action 条目。")
    if concept.metrics and "metric" not in kinds:
        gaps.append(f"- 指标 {len(concept.metrics)} 个：本版没有一条 metric 条目。")
    if concept.relations:
        member_ids = {str(row.get("canonical_id")) for row in meanings
                      if row.get("kind") == "entity" and row.get("business_type") == concept.concept_id}
        related = sum(1 for row in meanings
                      if row.get("kind") == "relation"
                      and str(row.get("canonical_subject_id")) in member_ids)
        if member_ids and not related:
            gaps.append(f"- 关系 {len(concept.relations)} 条：本版没有一条以这个类型为主语的关系。")
    return gaps


def _concept_pages(meanings: Sequence[Mapping[str, Any]],
                   concept_set: Any = None,
                   concept_state: Mapping[str, Any] | None = None) -> list[Page]:
    by_type = _type_members(meanings, concept_state)
    pages: list[Page] = []
    declared: set[str] = set()
    concepts = tuple(getattr(concept_set, "concepts", ()) or ())
    for concept in concepts:
        declared.add(concept.concept_id)
        members = sorted(set(by_type.get(concept.concept_id, [])))
        meta = META_KINDS.get(concept.meta_kind)
        fields = [
            ("type", _CONCEPT),
            ("title", concept.name),
            ("concept_id", concept.concept_id),
            ("meta_kind", concept.meta_kind),
            ("grounding", meta.grounding if meta else "scope_defined"),
            ("criteria", concept.criteria),
            ("aliases", list(concept.aliases)),
            ("member_count", len(members)),
            ("attributes", len(concept.attributes)),
            ("relations", len(concept.relations)),
            ("constraints", len(concept.constraints)),
            ("actions", len(concept.actions)),
            ("metrics", len(concept.metrics)),
            ("concept_set_version", getattr(concept_set, "version_id", None)),
            ("origin", concept.origin),
            ("generated_from", f"{PROJECTION_VERSION}:concept:{concept.concept_id}"),
        ]
        body = [_frontmatter(fields), "", f"# {concept.name}（{concept.concept_id}）", "",
                "> 类型层：这一页说的是这个 scope 对一类事物的定义，不是任何一条被接受的实例。", "",
                "## 判据", "", concept.criteria, ""]
        if concept.aliases:
            body.append("## 其他写法")
            body.extend(f"- {name}" for name in concept.aliases)
            body.append("")
        structure = _declared_structure_lines(concept)
        if structure:
            body.append("## 声明的结构")
            body.append("")
            body.extend(structure)
        body.append("## 已接受的成员")
        body.extend(f"- {name}" for name in members)
        if not members:
            body.append("- 还没有任何已接受的实体带这个类型。")
        body.append("")
        gaps = _declared_gaps(concept, meanings)
        if gaps:
            body.append("## 还缺什么")
            body.extend(gaps)
            body.append("")
        pages.append(Page(path=f"concepts/{_safe(concept.concept_id)}.md", kind=_CONCEPT,
                          title=concept.name, content="\n".join(body)))
    for type_id in sorted(set(by_type) - declared):
        members = sorted(set(by_type[type_id]))
        meta = META_KINDS.get(type_id)
        title = meta.name if meta else type_id
        criteria = meta.criteria if meta else "来源自定义的类型；本 scope 的概念集没有为它给出判据。"
        body = [_frontmatter([
            ("type", _CONCEPT),
            ("title", title),
            ("concept_id", type_id),
            ("grounding", meta.grounding if meta else "scope_defined"),
            ("member_count", len(members)),
            ("declared_by_scope", False),
            ("generated_from", f"{PROJECTION_VERSION}:concept:{type_id}"),
        ]), "", f"# {title}（{type_id}）", "",
            "> 这个类型不在本 scope 的概念集里：要么它还没被声明，要么它是别的 scope 的词。", "",
            "## 判据", "", criteria, "",
            "## 已接受的成员", ""]
        body.extend(f"- {name}" for name in members)
        body.append("")
        pages.append(Page(path=f"concepts/{_safe(type_id)}.md", kind=_CONCEPT,
                          title=title, content="\n".join(body)))
    return pages


def _named_meaning(meaning_id: str, *collections: Mapping[str, Any]) -> str:
    """How a reviewer recognises a meaning id: its key and its own words."""
    for meanings in collections:
        row = meanings.get(meaning_id)
        if isinstance(row, Mapping):
            text = str(row.get("meaning") or "").strip()
            return f"{row.get('key') or meaning_id}" + (f" — {text[:80]}" if text else "")
    return "（本版本不再持有这一条）"


def _diff_lines(label: str, ids: Sequence[str], *collections: Mapping[str, Any]) -> list[str]:
    lines = [f"- {label} {len(ids)} 条"]
    for meaning_id in list(ids)[:_LIST_CAP]:
        lines.append(f"  - `{_short(meaning_id, 16)}` {_named_meaning(meaning_id, *collections)}")
    if len(ids) > _LIST_CAP:
        lines.append(f"  - …另有 {len(ids) - _LIST_CAP} 条未列出")
    return lines


def _version_pages(state: Mapping[str, Any]) -> list[Page]:
    """One page per accepted version: what it overrides, what it changed, what it says."""
    versions = state.get("accepted_versions") or {}
    active_id = state.get("active_version_id")
    pages: list[Page] = []
    for version_id in sorted(versions):
        version = versions[version_id]
        if not isinstance(version, Mapping):
            continue
        raw_meanings = version.get("meanings")
        meanings: Mapping[str, Any] = dict(raw_meanings) if isinstance(raw_meanings, Mapping) else {}
        parent_id = version.get("parent_version_id")
        parent = versions.get(parent_id, {}) if isinstance(parent_id, str) else {}
        raw_parent = parent.get("meanings")
        parent_meanings: Mapping[str, Any] = dict(raw_parent) if isinstance(raw_parent, Mapping) else {}
        diff = version.get("diff") if isinstance(version.get("diff"), Mapping) else None
        is_active = version_id == active_id
        basis = version.get("owner_acceptance_basis")
        basis = basis if isinstance(basis, Mapping) else None
        if basis is None:
            admission = ("业务批准依据：未记录业务批准依据"
                         "（这个版本没有保存 `owner_acceptance_basis`）。本页不替你补一条。")
        else:
            issued = basis.get("issued_at")
            admission = (f"业务批准依据：receipt `{basis.get('receipt_id') or '未记录'}`，"
                         f"issuer `{basis.get('issuer_id') or '未记录'}`，"
                         f"receipt 类别 `{basis.get('receipt_type') or '未记录'}`，"
                         f"签发 {issued if isinstance(issued, int) else '未记录'}。"
                         "这是该版本被接受时保存的签发记录；test_only 不等于企业 Owner 批准。")
        body = [_frontmatter([
            ("type", _VERSION),
            ("title", f"版本 {_short(version_id, 16)}"),
            ("version_id", version_id),
            ("parent_version_id", parent_id),
            ("candidate_id", version.get("candidate_id")),
            ("decision_id", version.get("decision_id")),
            ("source_id", version.get("source_id")),
            ("source_revision", version.get("source_revision")),
            ("authority_class", version.get("authority_class")),
            ("owner_acceptance_basis", "recorded" if basis else "missing"),
            ("acceptance_basis_receipt", basis.get("receipt_id") if basis else None),
            ("acceptance_basis_issuer", basis.get("issuer_id") if basis else None),
            ("active", is_active),
            ("meaning_count", len(meanings)),
            ("confirmed_by_absence_count", version.get("confirmed_by_absence_count")),
            ("generated_from", f"{PROJECTION_VERSION}:version:{version_id}"),
        ]), "", f"# 版本 {version_id}", "",
            f"> 权威：{'当前生效' if is_active else '已被取代（当前生效 `' + str(active_id) + '`）'}"
            f"（作者类别 `{version.get('authority_class') or 'unknown'}`）；"
            f"来源 `{version.get('source_id')}`、修订 `{_short(version.get('source_revision'))}`。",
            f"> 准入：作者类别 `{version.get('authority_class') or 'unknown'}`；{admission}", ""]

        body.append("## 改了什么")
        if diff is None:
            body.append("- 这个版本在接受时没有保留比较；`ontology version diff --version-id` 会从它和父版本"
                        "重算，并把 `source` 报为 `computed`。")
        else:
            body.append(f"- 相对父版本 `{parent_id or '（无）'}`：新增/修改/移除与证据增减如下，"
                        "每条 id 取自接受时保存的那份比较。")
            body.append("")
            body.extend(_diff_lines("新增", diff.get("added_meaning_ids") or [], meanings))
            body.extend(_diff_lines("修改", diff.get("changed_meaning_ids") or [], meanings, parent_meanings))
            body.extend(_diff_lines("移除", diff.get("removed_meaning_ids") or [], parent_meanings))
            body.extend(_diff_lines("证据增加", diff.get("evidence_added_meaning_ids") or [], meanings))
            body.extend(_diff_lines("证据减少", diff.get("evidence_removed_meaning_ids") or [],
                                    meanings, parent_meanings))
            carried = diff.get("carried_meaning_ids") or []
            if carried:
                body.extend(_diff_lines("原文仍在、本次未提及而保留", carried, meanings))
        body.append("")

        body.append("## 这个版本说了什么")
        kinds: dict[str, list[Mapping[str, Any]]] = {}
        for row in meanings.values():
            if isinstance(row, Mapping):
                kinds.setdefault(str(row.get("kind") or "unknown"), []).append(row)
        for kind in sorted(kinds):
            rows = kinds[kind]
            body.append(f"### {kind}（{len(rows)}）")
            for row in rows[:_LIST_CAP]:
                body.append(f"- {row.get('key') or row.get('meaning_id')} — {str(row.get('meaning') or '')[:100]}")
            if len(rows) > _LIST_CAP:
                body.append(f"- …另有 {len(rows) - _LIST_CAP} 条未列出")
            body.append("")
        if not kinds:
            body.append("- 这个版本没有持有任何 meaning。")
            body.append("")
        pages.append(Page(path=f"versions/{_safe(version_id)}.md", kind=_VERSION,
                          title=f"版本 {_short(version_id, 16)}", content="\n".join(body)))
    return pages


def _gaps_page(wiki: Any, meanings: Sequence[Mapping[str, Any]],
               sources: Sequence[Mapping[str, Any]], concept_set: Any,
               concept_state: Mapping[str, Any] | None,
               state: Mapping[str, Any]) -> Page:
    """What a reader cannot yet rely on, written where a reader will look for it."""
    entities = [row for row in meanings if row.get("kind") == "entity"]
    relations = [row for row in meanings if row.get("kind") == "relation"]
    by_type = _type_members(meanings, concept_state)
    declared = {concept.concept_id for concept in (getattr(concept_set, "concepts", ()) or ())}
    untyped = [row for row in entities
               if not isinstance(row.get("business_type"), str) or not str(row.get("business_type") or "").strip()]
    outside = sorted(set(by_type) - declared) if declared else []

    touched: set[str] = set()
    for row in relations:
        for field_name in ("canonical_subject_id", "canonical_object_id"):
            value = row.get(field_name)
            if isinstance(value, str) and value:
                touched.add(value)
    isolated = [row for row in entities
                if isinstance(row.get("canonical_id"), str) and row["canonical_id"] not in touched]
    unlinked = [row for row in entities
                if not any(evidence.get("span_sha256") for evidence in (row.get("evidence") or []))]

    body = [_frontmatter([
        ("type", _GAPS),
        ("title", "缺口"),
        ("scope_id", state.get("scope_id")),
        ("generated_from", PROJECTION_VERSION),
    ]), "", "# 缺口", "",
        "> 这一页只说「还缺什么」，不改变任何知识；每一项都来自store已经记下的东西。", ""]

    body.append(f"## 未被类型化的实体（{len(untyped)}）")
    if untyped:
        body.extend(f"- {row.get('meaning') or row.get('key')}" for row in untyped[:_LIST_CAP])
        if len(untyped) > _LIST_CAP:
            body.append(f"- …另有 {len(untyped) - _LIST_CAP} 个未列出")
    else:
        body.append("- 没有：每个已接受实体都带类型。")
    body.append("")

    body.append(f"## 类型不在本 scope 概念集里的实体（{sum(len(by_type[key]) for key in outside)}）")
    if outside:
        for type_id in outside:
            body.append(f"- `{type_id}`：{len(by_type[type_id])} 个实体；这个类型没有声明，所以没有判据可依。")
    else:
        body.append("- 没有：所有类型都在概念集里。")
    body.append("")

    body.append(f"## 没有任何关系的实体（{len(isolated)}）")
    if isolated:
        body.extend(f"- {row.get('meaning') or row.get('key')}"
                    for row in isolated[:_LIST_CAP])
        if len(isolated) > _LIST_CAP:
            body.append(f"- …另有 {len(isolated) - _LIST_CAP} 个未列出")
    else:
        body.append("- 没有：每个实体都至少被一条关系触到。")
    body.append("")

    body.append("## 没有逐行证据的实体（{}）".format(len(unlinked)))
    if unlinked:
        body.extend(f"- {row.get('meaning') or row.get('key')}" for row in unlinked[:_LIST_CAP])
    else:
        body.append("- 没有：每个实体都带着它被读到的位置。")
    body.append("")

    unresolved = [
        {"concept_id": concept.concept_id, "predicate": relation.predicate, "target": relation.target}
        for concept in (getattr(concept_set, "concepts", ()) or ())
        for relation in concept.relations
        if relation.target not in declared and relation.target not in META_KINDS
    ]
    body.append(f"## 声明的关系指向概念集以外（{len(unresolved)}）")
    if unresolved:
        body.extend(f"- `{row['concept_id']}` —{row['predicate']}→ `{row['target']}`：目标不在概念集里，"
                    "也没有对到上层种类。" for row in unresolved[:_LIST_CAP])
    else:
        body.append("- 没有：每条声明的关系都指向本 scope 的概念或上层种类。")
    body.append("")

    kinds = {str(row.get("kind")) for row in meanings}
    declared_actions = sum(len(concept.actions) for concept in (getattr(concept_set, "concepts", ()) or ()))
    declared_constraints = sum(len(concept.constraints) for concept in (getattr(concept_set, "concepts", ()) or ()))
    declared_metrics = sum(len(concept.metrics) for concept in (getattr(concept_set, "concepts", ()) or ()))
    body.append("## 类型声明了、本版还没读到的结构")
    body.append(f"- 动作：声明 {declared_actions} 个，本版 action 条目 {len([row for row in meanings if row.get('kind') == 'action'])} 条")
    body.append(f"- 约束：声明 {declared_constraints} 条，本版 constraint 条目 "
                f"{len([row for row in meanings if row.get('kind') == 'constraint'])} 条")
    body.append(f"- 指标：声明 {declared_metrics} 个，本版 metric 条目 "
                f"{len([row for row in meanings if row.get('kind') == 'metric'])} 条")
    if not (declared_actions or declared_constraints or declared_metrics):
        body.append("- 概念集还没有声明动作、约束或指标；这几个数字为 0 是因为类型层还没说话。")
    body.append(f"- 本版出现的条目种类：{', '.join(sorted(kinds)) or '（无）'}")
    body.append("")

    versions = state.get("accepted_versions") or {}
    active_id = state.get("active_version_id")
    stale = sorted(key for key in versions
                   if key != active_id and isinstance(versions[key], Mapping))
    body.append(f"## 已接受但未生效的版本（{len(stale)}）")
    if stale:
        body.extend(f"- `{version_id}`：仍可读，读它的投影是另一件事，页面只投影当前生效的一点。" for version_id in stale[:_LIST_CAP])
    else:
        body.append("- 没有：已接受的版本就是当前生效的版本。")
    body.append("")

    present = _present_sources(wiki, sources)
    missing = [row for row in sources if str(row.get("source_id")) not in present]
    partial = [row for row in sources
               if str((row.get("extraction") or {}).get("status") or "") not in {"", "complete"}]
    body.append(f"## 来源的缺口（缺文件 {len(missing)}，读取不完整 {len(partial)}）")
    for row in missing[:_LIST_CAP]:
        body.append(f"- `{row.get('relative_path')}`：原始文件不在任何 Wiki 根目录下，它支撑的证据无法校验。")
    for row in partial[:_LIST_CAP]:
        raw_extraction = row.get("extraction")
        extraction: Mapping[str, Any] = dict(raw_extraction) if isinstance(raw_extraction, Mapping) else {}
        body.append(f"- `{row.get('relative_path')}`：读取状态 `{extraction.get('status')}`"
                    f"（单元 {extraction.get('unit_count', 0)}，截断 {bool(extraction.get('truncated'))}）。")
    if not missing and not partial:
        body.append("- 没有：每份来源都在，且都读完整了。")
    body.append("")
    return Page(path="gaps.md", kind=_GAPS, title="缺口", content="\n".join(body))


def _present_sources(wiki: Any, sources: Sequence[Mapping[str, Any]]) -> set[str]:
    """Which staged identities still have a file under one of the declared roots."""
    present: set[str] = set()
    roots = tuple(getattr(wiki, "roots", ()) or ())
    for source in sources:
        relative = str(source.get("relative_path") or "")
        if not relative:
            continue
        if any((Path(root) / relative).is_file() for root in roots):
            present.add(str(source.get("source_id")))
    return present


def _source_pages(sources: Sequence[Mapping[str, Any]], scan: Mapping[str, Sequence[_TextUnit]],
                  index: EntityIndex, present: set[str] | None = None) -> list[Page]:
    pages = []
    for source in sources:
        source_id = str(source.get("source_id"))
        relative = str(source.get("relative_path") or source_id)
        raw_extraction = source.get("extraction")
        extraction: Mapping[str, Any] = dict(raw_extraction) if isinstance(raw_extraction, Mapping) else {}
        units = scan.get(source_id, ())
        scan_row = scan_units(index, units) if units else None

        body = [_frontmatter([
            ("type", _SOURCE),
            ("title", relative),
            ("source_id", source_id),
            ("format", source.get("source_format") or "markdown"),
            ("revision", str(source.get("revision") or "")),
            ("extraction_status", extraction.get("status") or source.get("content_status") or "UNKNOWN"),
            ("units", extraction.get("unit_count", len(units))),
            ("locators", extraction.get("locator_count")),
            ("truncated", bool(extraction.get("truncated"))),
            ("vision_missing", len(extraction.get("vision_missing") or [])),
            ("generated_from", f"{PROJECTION_VERSION}:{source_id}"),
        ]), "", f"# {relative}", ""]

        body.append("## 抽取完整度")
        body.append(f"- 状态：`{extraction.get('status', 'UNKNOWN')}`；"
                    f"单元 {extraction.get('unit_count', 0)} / 定位符 {extraction.get('locator_count', 0)}")
        if extraction.get("truncated"):
            body.append("- **这份文件只读了一部分**：定位符数量超过上限，未读部分没有进入证据。")
        if extraction.get("part_errors"):
            body.append(f"- 无法解析的部件：{len(extraction['part_errors'])} 个"
                        f"（{', '.join(extraction['part_errors'][:3])}）")
        if extraction.get("vision_missing"):
            body.append(f"- 图文未读：{len(extraction['vision_missing'])} 处（图片/版式中的文字没有进入证据）")
        shrink = extraction.get("shrink_suspect")
        if isinstance(shrink, dict):
            body.append(
                f"- **这次只读到上一次的 {shrink.get('ratio', 0):.0%}**："
                f"同一份字节上次 {shrink.get('previous_unit_count')} 单元，这次 "
                f"{shrink.get('unit_count')} 单元；更像解析退化，不像文件变短。"
            )
        for warning in list(extraction.get("warnings") or [])[:5]:
            body.append(f"- 警告：`{warning}`")
        if present is not None and source_id not in present:
            # The identity stays — a document that entered the shelf does not stop existing
            # because its file moved away — but nothing above it can be checked any more.
            body.append("- **原始文件当前不在任何 Wiki 根目录下**：这份身份仍然保留，"
                        "但它所支撑的证据无法校验，页面上只能标为 `unknown`。")
        body.append("")

        body.append("## 提及")
        if scan_row is None:
            body.append("- 本次投影没有扫描这份来源。")
        else:
            body.append(f"- 提及 {scan_row['mention_count']} 处，其中可信 {scan_row['confident_mention_count']}，"
                        f"歧义 {scan_row['ambiguous_count']}；覆盖 {scan_row['distinct_confident']} 个已接受实体。")
        body.append("")
        pages.append(Page(path=f"sources/{_safe(source_id)}.md", kind=_SOURCE,
                          title=relative, content="\n".join(body)))
    return pages


def _overview_page(wiki: Any, meanings: Sequence[Mapping[str, Any]], sources: Sequence[Mapping[str, Any]],
                   stats: Mapping[str, Any], accepted: Mapping[str, Any]) -> Page:
    freshness: dict[str, int] = {}
    for row in meanings:
        key = str(row.get("freshness_status") or "unknown")
        freshness[key] = freshness.get(key, 0) + 1
    extraction_counts: dict[str, int] = {}
    # A source that is not complete says why, so "how much of this Wiki was actually read"
    # is answerable from the overview instead of from every page.
    reasons = {"图片或版式未读": 0, "超过上限被截断": 0, "部件解析失败": 0, "读取退化（缩水）": 0, "其他": 0}
    for source in sources:
        raw_extraction = source.get("extraction")
        extraction: Mapping[str, Any] = dict(raw_extraction) if isinstance(raw_extraction, Mapping) else {}
        key = str(extraction.get("status") or "unknown")
        extraction_counts[key] = extraction_counts.get(key, 0) + 1
        if key == "complete":
            continue
        hit = False
        if extraction.get("vision_missing"):
            reasons["图片或版式未读"] += 1
            hit = True
        if extraction.get("truncated"):
            reasons["超过上限被截断"] += 1
            hit = True
        if extraction.get("part_errors"):
            reasons["部件解析失败"] += 1
            hit = True
        if isinstance(extraction.get("shrink_suspect"), Mapping):
            reasons["读取退化（缩水）"] += 1
            hit = True
        if not hit:
            reasons["其他"] += 1

    receipts = []
    try:
        from .knowledge_novelty import read_receipts

        receipts = read_receipts(wiki.workspace)
    except Exception:  # noqa: BLE001 - a missing receipt directory is not a page failure
        receipts = []

    unattached = list(stats.get("unattached") or [])
    object_lines = [f"- 业务对象：职责 {stats.get('duties', 0)} 条、事件 {stats.get('events', 0)} 条、"
                    f"条件 {stats.get('conditions', 0)} 条；其中未挂到任何对象 {len(unattached)} 条"]
    if unattached:
        shown = "、".join(unattached[:20])
        object_lines.append(f"  - 未挂到对象：{shown}"
                            + (f" 等 {len(unattached)} 条" if len(unattached) > 20 else ""))
    body = [_frontmatter([
        ("type", _OVERVIEW),
        ("title", "概览"),
        ("scope_id", accepted.get("scope_id")),
        ("active_version", accepted.get("active_version_id")),
        ("generated_from", PROJECTION_VERSION),
    ]), "", "# 概览", "",
        "## 这个 Wiki 里有什么", "",
        f"- 来源 {stats['sources']} 份；已接受版本 {accepted.get('active_version_id') or '（尚无）'}",
        f"- 实体 {stats['entities']} 个；关系 {stats['relations']} 条；规则/条件/缺失断言 {stats['claims']} 条",
        f"- 已接受的版本 {stats.get('versions', 0)} 个；还缺什么见 [[缺口]]",
        *object_lines, ""]

    body.append("## 来源的读取完整度")
    if extraction_counts:
        for key in sorted(extraction_counts):
            body.append(f"- `{key}`：{extraction_counts[key]} 份")
    else:
        body.append("- 尚无来源。")
    incomplete = {key: value for key, value in reasons.items() if value}
    if incomplete:
        body.append("- 为什么不是 `complete`（一份来源可能不止一个原因）：")
        for key in ("图片或版式未读", "超过上限被截断", "部件解析失败", "读取退化（缩水）", "其他"):
            if incomplete.get(key):
                body.append(f"  - {key}：{incomplete[key]} 份")
    body.append("")

    body.append("## 已接受知识的新鲜度")
    if freshness:
        for key in sorted(freshness):
            body.append(f"- `{key}`：{freshness[key]} 条")
    else:
        body.append("- 还没有接受的语义。")
    body.append("")

    if receipts:
        from .knowledge_novelty import TIERS
        from .knowledge_novelty import summarize as tier_summary

        tiers = tier_summary(receipts)
        body.append("## 本次没有花钱的原因")
        for tier in TIERS:
            if tiers.get(tier):
                body.append(f"- `{tier}`：{tiers[tier]} 份")
        body.append("")

    body.append("## 缺口")
    body.append("- 页面只投影已接受版本里的条目；候选生命周期（谁提的、审到哪一步）不在这里。"
                "条目自己的资格与未确认内容仍会显示，例如待审的职责与缺失断言。")
    body.append("")
    return Page(path="overview.md", kind=_OVERVIEW, title="概览", content="\n".join(body))


def _log_page(wiki: Any) -> Page:
    state = wiki.semantic_state()
    transitions = state.get("transitions") or []
    body = [_frontmatter([
        ("type", _LOG),
        ("title", "操作记录"),
        ("generated_from", PROJECTION_VERSION),
    ]), "", "# 操作记录", "",
        "由语义转换回执直接投影，不经过模型。", ""]
    for row in transitions[-200:]:
        body.append(f"- `{row.get('operation')}` · {row.get('actor_origin')} · "
                    f"{row.get('status')} · {str(row.get('transition_id'))[:16]}")
    if not transitions:
        body.append("- 尚无记录。")
    body.append("")
    return Page(path="log.md", kind=_LOG, title="操作记录", content="\n".join(body))


def _index_page(pages: Sequence[Page], root: Path | str | None) -> Page:
    diverged = set()
    if root is not None:
        diverged = set(diverged_pages(pages, root))
    body = [_frontmatter([
        ("type", _INDEX),
        ("title", "索引"),
        ("page_count", len(pages) + 1),
        ("generated_from", PROJECTION_VERSION),
    ]), "", "# 索引", ""]
    for kind in (_ENTITY, _CONCEPT, _VERSION, _SOURCE, _GAPS, _OVERVIEW, _LOG):
        rows = [page for page in pages if page.kind == kind]
        if not rows:
            continue
        body.append(f"## {kind}")
        body.append("")
        for page in rows:
            flag = " · `page_diverged`" if page.path in diverged else ""
            body.append(f"- [[{page.title}]] — `{page.path}`{flag}")
        body.append("")
    return Page(path="index.md", kind=_INDEX, title="索引", content="\n".join(body))


_LINK = re.compile(r"\[\[([^\]\n]+?)\]\]")


def _link_target(raw: str) -> str:
    """The page name a `[[...]]` link points at: an alias or a heading is not part of it."""
    return raw.split("|", 1)[0].split("#", 1)[0].strip()


def page_link_index(pages: Sequence[Page]) -> dict[str, tuple[str, ...]]:
    """The paths that carry each title, keyed by title.

    A title is a page's *name*, not its identity: two pages can carry the same one, and then a
    link that names it cannot say which page it meant. Both paths are kept so the caller can.
    """
    index: dict[str, list[str]] = {}
    for page in pages:
        title = page.title.strip()
        if title:
            index.setdefault(title, []).append(page.path)
    return {title: tuple(sorted(paths)) for title, paths in index.items()}


def link_report(pages: Sequence[Page]) -> dict[str, Any]:
    """Resolve every `[[title]]` link in the set to a file inside the same set.

    A link that renders is not a link that leads anywhere, and this is the difference: each
    title is resolved against the pages actually present. A title no page carries is
    ``unresolved`` - the reader follows a link into nothing - and a title more than one page
    carries is ``ambiguous`` - the set cannot say which file was meant, so picking the first
    one would be an invented answer. ``duplicate_titles`` is reported even when no link points
    at the pair, because the reuse is what makes a future name unresolvable.

    Every resolved edge is listed with the file it reaches, so a reader of the report can check
    the mapping without re-running the projection. This says where a title *resolves*. It says
    nothing about whether what the page cites is true or current: a `diverged` page, a
    relocated citation and an unresolved quote are all outside what a link check can vouch for.
    """
    index = page_link_index(pages)
    resolved: list[dict[str, str]] = []
    ambiguous: list[dict[str, Any]] = []
    unresolved: list[dict[str, str]] = []
    for page in pages:
        for match in _LINK.finditer(page.content):
            target = _link_target(match.group(1))
            paths = index.get(target, ())
            if len(paths) == 1:
                resolved.append({"title": target, "from": page.path, "path": paths[0]})
            elif paths:
                ambiguous.append({"title": target, "from": page.path, "paths": list(paths)})
            else:
                unresolved.append({"title": target, "from": page.path})
    return {
        "titles": len(index),
        "links": len(resolved) + len(ambiguous) + len(unresolved),
        # Every edge that resolves, as the file it reaches: the mapping itself, not a count of it.
        "resolved": resolved,
        "ambiguous": ambiguous,
        "unresolved": unresolved,
        "duplicate_titles": {title: list(paths) for title, paths in index.items() if len(paths) > 1},
    }


def _manifest_path(root: Path | str) -> Path:
    return Path(root).expanduser().resolve() / MANIFEST_NAME


@dataclass(frozen=True)
class _Manifest:
    """What a previous projection wrote: page digests, and what it was projected from."""

    pages: dict[str, str]
    identity: dict[str, Any] | None = None
    legacy: bool = False


def _read_manifest(root: Path | str) -> _Manifest:
    path = _manifest_path(root)
    if not path.is_file():
        return _Manifest({})
    try:
        loaded = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return _Manifest({})
    if not isinstance(loaded, dict):
        return _Manifest({})
    if isinstance(loaded.get("pages"), dict):
        pages = {key: value for key, value in loaded["pages"].items()
                 if isinstance(key, str) and isinstance(value, str)}
        identity = loaded.get("identity")
        return _Manifest(pages, identity if isinstance(identity, dict) else None)
    # A v1 manifest was one flat {path: sha256} map. Its digests still protect the pages it
    # names; it simply cannot say which store the tree came from.
    pages = {key: value for key, value in loaded.items()
             if isinstance(key, str) and isinstance(value, str)}
    return _Manifest(pages, None, legacy=True)


def _write_manifest(root: Path | str, pages: Mapping[str, str], identity: Mapping[str, Any] | None) -> None:
    """Replace the manifest in one step, so a reader never sees half a record."""
    document: dict[str, Any] = {
        "schema_version": MANIFEST_SCHEMA_VERSION,
        "pages": dict(sorted(pages.items())),
    }
    if identity is not None:
        document["identity"] = dict(identity)
    path = _manifest_path(root)
    temporary = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    try:
        temporary.write_text(
            json.dumps(document, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
        )
        os.replace(temporary, path)
    finally:
        if temporary.is_file():
            temporary.unlink()


def _page_path(root: Path, relative: Any, *, inside: str | None = None) -> Path | None:
    """The file one path names, or None when it is not a plain relative path inside ``root``.

    Every path this module writes or moves goes through here - a ``Page.path``, a manifest
    entry, an archive source and an archive destination - because a page set and a manifest
    both come from outside this module. Accepted: a relative path with no parent segment, no
    drive and no anchor whose resolved location really is inside the page root, and inside
    ``inside`` below it when given. A resolved path is what is checked, so a junction or a
    symlinked folder is judged by where it leads, not by how it is spelled.
    """
    if not isinstance(relative, str) or not relative:
        return None
    candidate = Path(relative)
    if candidate.is_absolute() or candidate.drive or candidate.anchor or ".." in candidate.parts:
        return None
    boundary = (root / inside).resolve() if inside is not None else root
    try:
        target = (root / candidate).resolve()
    except OSError:
        return None
    if not target.is_relative_to(root) or not target.is_relative_to(boundary):
        return None
    return target


def _page_location(root: Path, relative: Any) -> Path | None:
    """Where a page may live: never the manifest itself, never inside the archive folder."""
    if not isinstance(relative, str):
        return None
    candidate = Path(relative)
    if candidate.parts and candidate.parts[0] == OBSOLETE_DIR:
        return None
    if len(candidate.parts) == 1 and candidate.parts[0] == MANIFEST_NAME:
        return None
    return _page_path(root, relative)


def diverged_pages(pages: Sequence[Page], root: Path | str) -> tuple[str, ...]:
    """Pages a person changed since the projection wrote them; never overwritten.

    A file that already holds exactly what this projection would write is not diverged: the
    record is simply behind the tree, which is what a run interrupted after its page writes
    leaves behind. Only bytes that match neither the record nor the projection are a person's.
    """
    recorded = _read_manifest(root).pages
    root_path = Path(root).expanduser().resolve()
    diverged = []
    for page in pages:
        target = _page_location(root_path, page.path)
        if target is None or not target.is_file():
            continue
        expected = recorded.get(page.path)
        if expected is None:
            continue
        digest = hashlib.sha256(target.read_bytes()).hexdigest()
        if digest != page.sha256 and digest != expected:
            diverged.append(page.path)
    return tuple(sorted(diverged))


def _write_page(target: Path, content: str) -> None:
    """Write one page in place. A seam: a test can fail the second page of a run."""
    target.write_text(content, encoding="utf-8", newline="\n")


def _archive_page(target: Path, destination: Path) -> None:
    """Move one page to its archive address. A seam, like `_write_page`."""
    destination.parent.mkdir(parents=True, exist_ok=True)
    os.replace(target, destination)


def materialize(pages: Sequence[Page], root: Path | str, *, dry_run: bool = False,
                identity: Mapping[str, Any] | None = None) -> dict[str, Any]:
    """Publish what the projection owns, and never publish over what it does not.

    Each rule is one way a generated tree can be published without destroying work:

    - a page whose bytes a person changed is `diverged` and left exactly as it is;
    - a file this projection has no record of is `conflict` and left exactly as it is, because
      the store cannot regenerate text it never wrote;
    - a path outside the page root - in the page set or in the manifest - is `refused` before
      the first write, so no entry can write or move a file this tree does not own;
    - a page the store no longer produces is archived under ``.obsolete/<digest16>/`` when it
      is still what was written, and kept as `obsolete_kept` when it is not. The digest is the
      address, so a later page of the same name cannot overwrite an earlier one's history;
    - the manifest is replaced atomically, so a crash leaves the previous record or the new one.
      That is a commitment about the record, not about the batch: the pages themselves are
      written one by one, so a crash mid-run leaves a mix of old and new pages until the next
      run reconciles them.

    Publication is by entry, not by batch: a refused or conflicting entry is reported and
    skipped while the remaining pages are still published, and ``complete`` in the result says
    whether every entry was *published or retired*. Callers that need all or nothing must
    inspect ``complete`` - a returned result is not a claim that nothing was blocked, and the
    exit code, not the return value, is what says so on the command line.

    ``complete`` is about publication, not about the tree matching the store: a page in
    ``diverged`` was processed and deliberately left as a person wrote it, so a run can be
    complete while that page no longer equals what the projection would generate. Read
    ``diverged`` for "this page is not the current output", ``complete`` for "nothing was
    blocked or left behind".

    The manifest records the digest of every page written and the identity of what the pages
    were projected from. Pass ``identity`` (a ``PageSet``'s own) to keep it current.
    """
    root_path = Path(root).expanduser().resolve()
    manifest = _read_manifest(root_path)
    recorded = dict(manifest.pages)
    current = {page.path for page in pages}
    refused: list[str] = []
    targets: dict[str, Path] = {}
    obsolete: dict[str, Path] = {}
    for page in pages:
        target = _page_location(root_path, page.path)
        if target is None:
            refused.append(str(page.path))
        else:
            targets[page.path] = target
    for path in sorted(set(recorded) - current):
        target = _page_location(root_path, path)
        destination = _page_path(root_path, f"{OBSOLETE_DIR}/{'0' * 16}/{path}", inside=OBSOLETE_DIR)
        if target is None or destination is None:
            # Leave the record in place: the manifest is wrong, and saying so every run is
            # better than quietly dropping the entry that names the file.
            refused.append(path)
        else:
            obsolete[path] = target
    written: list[str] = []
    skipped: list[str] = []
    diverged: list[str] = []
    conflicts: list[str] = []
    archived: list[str] = []
    obsolete_kept: list[str] = []
    for page in pages:
        target = targets.get(page.path)
        if target is None:
            continue
        expected = page.content
        if target.is_file():
            known = recorded.get(page.path)
            if target.read_text(encoding="utf-8") == expected:
                skipped.append(page.path)
                recorded[page.path] = page.sha256
                continue
            on_disk = hashlib.sha256(target.read_bytes()).hexdigest()
            if known is None:
                conflicts.append(page.path)
                continue
            if on_disk != known:
                diverged.append(page.path)
                continue
        if not dry_run:
            target.parent.mkdir(parents=True, exist_ok=True)
            _write_page(target, expected)
            recorded[page.path] = page.sha256
        written.append(page.path)
    for path, target in obsolete.items():
        if not target.is_file():
            recorded.pop(path)
            continue
        digest = hashlib.sha256(target.read_bytes()).hexdigest()
        if digest != recorded[path]:
            obsolete_kept.append(path)
            continue
        if not dry_run:
            destination = _page_path(
                root_path, f"{OBSOLETE_DIR}/{digest[:16]}/{path}", inside=OBSOLETE_DIR)
            if destination is None:
                refused.append(path)
                continue
            if destination.is_file() and hashlib.sha256(destination.read_bytes()).hexdigest() == digest:
                # These exact bytes are already archived under their own digest: this page is
                # the same history, not a newer one, so the existing copy stays the record.
                target.unlink()
            else:
                _archive_page(target, destination)
            recorded.pop(path)
        archived.append(path)
    identity_changed = identity is not None and manifest.identity != dict(identity)
    if not dry_run:
        _write_manifest(root_path, recorded, dict(identity) if identity is not None else manifest.identity)
    return {
        "root": str(root_path),
        "written": sorted(written),
        "skipped": sorted(skipped),
        "diverged": sorted(diverged),
        "conflicts": sorted(conflicts),
        "refused": sorted(set(refused)),
        "archived": sorted(archived),
        "obsolete_kept": sorted(obsolete_kept),
        "identity_changed": identity_changed,
        # The tree is exactly what the projection describes: nothing was refused, nothing on
        # disk conflicts, and no page the store no longer produces was left behind.
        "complete": not (conflicts or refused or obsolete_kept),
        "page_count": len(pages),
        "dry_run": dry_run,
    }
