"""A resident wiki that is a projection of what was accepted, not a model's output.

Every page here is a pure function of the store: accepted meanings, their evidence,
the source records, and (when supplied) the deterministic mention scan. Nothing on a
page is written by a model, so a page can be regenerated byte-identically, and a page
that a person edits is never mistaken for knowledge — it is reported as diverged.

The shape is the one a document-to-wiki product is expected to have —
``entities/``, ``concepts/``, ``sources/``, ``overview.md``, ``index.md``, ``log.md``,
YAML frontmatter — while the authority stays where it already is: in the accepted
version, with line-level evidence behind it.
"""

